// Match file offset as well as bytes: the universal file has an identical ARM mask.
static unsigned applyAdvSets24H32(void *data, size_t size, unsigned long long pageOffset) {
    unsigned applied = 0;
    auto page = static_cast<unsigned char *>(data);
    if (!page || size != 4096) return 0;
    for (unsigned i = 0; i < sizeof(advSetPatches24H32) / sizeof(advSetPatches24H32[0]); ++i) {
        const auto &patch = advSetPatches24H32[i];
        if (pageOffset != (patch.fileOffset & ~4095ULL)) continue;
        const size_t offset = patch.fileOffset & 4095ULL;
        if (patch.size > size - offset) continue;
        if (memcmp(page + offset, patch.original, patch.size) == 0) {
            memcpy(page + offset, patch.patched, patch.size);
            applied |= 1U << i;
        }
    }
    return applied;
}
