// Preserve Apple's completion, cancellation and advertising handle ownership.
#pragma once
static bool advSetsBuildMatches24H32(const char *build) {
    return build && strncmp(build, "24H32", 6) == 0;
}
struct AdvSetPatch24H32 {
    const char *name;
    unsigned long long fileOffset;
    unsigned char original[16];
    unsigned char patched[16];
    size_t size;
};
